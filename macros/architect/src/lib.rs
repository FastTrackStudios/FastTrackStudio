//! `architect` — one derive, one struct, every surface.
//!
//! Users write:
//!
//! ```ignore
//! #[derive(architect::Entity)]
//! #[architect(table_name = "examples", repo)]
//! pub struct Example {
//!     #[architect(primary_key, on_create = Uuid::new_v4())]
//!     pub id: Uuid,
//!     #[architect(filterable, sortable, fulltext)]
//!     pub name: String,
//! }
//! ```
//!
//! and get, from one definition:
//!
//! - The wasm-clean wire struct (with `facet::Facet` derived)
//! - `ExampleCreate` / `ExampleUpdate` / `ExampleList` payload types
//! - The `ExampleRepo` `#[vox::service]` trait (typed RPC for the wire)
//! - `ExampleClient` auto-generated by vox for browser / desktop / iOS
//! - With `--features server`, the full SeaORM `Model` + `Entity` +
//!   `Column` + `Relation` + `ActiveModel`, plus an
//!   `ExampleRepoStorage<C: ConnectionTrait>` that implements the repo
//!   trait against a SeaORM connection.
//!
//! Wire encoding is **facet-only**. Vox already speaks facet on its
//! transport layer, so architect types travel as a coherent system
//! with zero per-type serde glue.

pub use architect_derive::Entity;

// Re-export facet + vox so user crates can `use architect::Facet` /
// `use architect::vox::service` without taking those crates as
// separate direct dependencies. Keeps the consumer Cargo.toml short.
pub use facet;
pub use vox;

// ── Repository error envelope ──────────────────────────────────────────

/// Error returned by every architect-generated repo method. Tight on
/// purpose — new variants are a wire-format change for every existing
/// `<Entity>Repo` trait.
#[derive(Debug, Clone, PartialEq, Eq, facet::Facet, thiserror::Error)]
#[repr(u8)]
pub enum RepoError {
    #[error("entity not found")]
    NotFound,
    #[error("invalid input: {0}")]
    InvalidInput(String),
    #[error("conflict: {0}")]
    Conflict(String),
    #[error("internal error: {0}")]
    Internal(String),
}

// ── Pagination + sort + filter primitives (wire-safe) ──────────────────

#[derive(Debug, Clone, PartialEq, Eq, facet::Facet, Default)]
pub struct Page {
    /// Zero-indexed page number.
    pub index: u32,
    /// Items per page. Implementations clamp to a sane max.
    pub size: u32,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, facet::Facet)]
#[repr(u8)]
pub enum SortOrder {
    Asc,
    Desc,
}

#[derive(Debug, Clone, PartialEq, Eq, facet::Facet)]
pub struct Sort {
    /// Field name (matches the API struct's snake_case identifier).
    pub field: String,
    pub order: SortOrder,
}

/// Free-form filter expression. Parsed server-side from a JSON-shaped
/// string for now; an evolving structured form lands as the macro
/// grows.
#[derive(Debug, Clone, PartialEq, Eq, facet::Facet, Default)]
pub struct Filter {
    pub raw: String,
}

// ── Storage trait (server-only) ────────────────────────────────────────
//
// The macro-generated `<Entity>RepoStorage<C>` parameterizes over a
// SeaORM connection and implements the `<Entity>Repo` vox trait. The
// glue is mechanical; this trait lets architect's emitted impl call
// into SeaORM through a stable API.

#[cfg(feature = "server-axum")]
pub mod axum_ws;

#[cfg(feature = "server")]
pub mod storage {
    //! Generic storage helpers used by macro-emitted code.

    use sea_orm::ConnectionTrait;

    /// Bound the macro's emitted repository structs use for their
    /// connection generic. Kept here so the macro doesn't have to
    /// emit the long trait list at every callsite.
    pub trait DbConn: ConnectionTrait + Clone + Send + Sync + 'static {}

    impl<T> DbConn for T where T: ConnectionTrait + Clone + Send + Sync + 'static {}
}
